from __future__ import annotations

# adr_index.py -- writes docs/architecture/adr/README.md, the index of every ADR, from each
# file's own H1 line, so the index cannot drift from the ADRs it lists.
#
# The titles are taken as written; the index adds no status column, because the ADRs record
# their status in several different shapes (a "Status:" line, a status-update section, a
# superseded note in a blockquote) and a status read wrongly would mislead more than none.
#
# Usage: python scripts/adr_index.py           (rewrite the index)
#        python scripts/adr_index.py --check   (exit 1 if the index is stale; CI and the test)
import argparse
import re
import sys
from pathlib import Path

ADR_DIR = Path(__file__).resolve().parent.parent / "docs" / "architecture" / "adr"
INDEX_NAME = "README.md"
# "# 0001. Title" and "# ADR-0038: Title" are both in use.
_H1 = re.compile(r"^#\s+(?:ADR-)?(\d{4})[.:]\s*(.+?)\s*$")


def render(adr_dir: Path) -> str:
    rows: list[str] = []
    numbers: list[str] = []
    for path in sorted(adr_dir.glob("[0-9][0-9][0-9][0-9]-*.md")):
        first = path.read_text(encoding="utf-8").splitlines()[0] if path.stat().st_size else ""
        match = _H1.match(first)
        if match is None or match.group(1) != path.name[:4]:
            raise ValueError(f"{path.name}: the first line must be '# NNNN. Title' (got {first!r})")
        title = match.group(2).replace("|", "\\|")
        numbers.append(match.group(1))
        rows.append(f"| {match.group(1)} | [{title}]({path.name}) |")
    shared = sorted({n for n in numbers if numbers.count(n) > 1})
    note = f" These numbers are used by more than one ADR: {', '.join(shared)}." if shared else ""
    return (
        "# Architecture decision records\n\n"
        "Generated by `scripts/adr_index.py` from each ADR's first line; do not edit by hand.\n"
        "Each ADR states its own status, and later addenda or superseding ADRs are noted inside\n"
        f"it.{note}\n\n"
        "| ADR | Title |\n|---|---|\n" + "\n".join(rows) + "\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if the index is stale")
    args = parser.parse_args(argv)
    want = render(ADR_DIR)
    index = ADR_DIR / INDEX_NAME
    have = index.read_text(encoding="utf-8").replace("\r\n", "\n") if index.exists() else ""
    if args.check:
        if have != want:
            print(f"{index} is stale: run python scripts/adr_index.py")
            return 1
        return 0
    index.write_text(want, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
